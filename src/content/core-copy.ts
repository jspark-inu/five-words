/**
 * 통합 칸 "명식 한가운데" 줄의 뒷말. 상대 기운이 중심(격 무리)을 낳아 받치거나(생) 누를 때(극)만 쓰고,
 * 그 힘이 이 단어에 무슨 뜻인지로 말한다. 중심이 상대를 낳거나 누르는 방향이면 단어와 바로 이어지지 않아 쓰지 않는다.
 * center는 "편인(偏印)", rival은 "재성(財星)"처럼 읽기와 한자를 함께 적은 이름, word는 단어.
 */
export function coreBridge(kind: 'match' | 'clash', act: '생' | '극', center: string, rival: string, word: string): string {
  // "편인(偏印)"처럼 한자가 붙은 이름은 괄호 앞 한글로 조사를 고른다.
  const fc = (s: string) => hasFinalConsonant(s.replace(/\([^)]*\)$/, ''))
  const i = (s: string) => (fc(s) ? '이' : '가')
  const eul = (s: string) => (fc(s) ? '을' : '를')
  const gwa = (s: string) => (fc(s) ? '과' : '와')
  const eun = (s: string) => (fc(s) ? '은' : '는')
  if (kind === 'clash' && act === '극') return `그런데 이 ${center}${eul(center)} ${rival}${i(rival)} 누르고 있습니다. 한가운데가 눌린 만큼 ${word}${i(word)} 이 중심과 부딪히면서도 앞에 나온 것으로 읽을 수 있습니다.`
  if (kind === 'clash') return `${rival}${i(rival)} 이 ${center}${eul(center)} 받쳐 주어 한가운데가 단단합니다. ${word}${gwa(word)}의 부딪힘이 쉽게 사라지지 않으니 아래 질문을 오래 들고 가 보세요.`
  if (act === '생') return `${rival}${i(rival)} 이 ${center}${eul(center)} 받쳐 주어, ${word}${i(word)} 명식에서 더 단단하게 받쳐집니다.`
  return `다만 ${rival}${i(rival)} 이 ${center}${eul(center)} 누르고 있어서, ${word}${eun(word)} 바쁠 때 먼저 밀려나기 쉽습니다.`
}
