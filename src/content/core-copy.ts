/** 격 문장. byTouchul이면 "월지에 ○○이 앉아"를 "월지의 숨은 글자 ○○이 천간에 드러나"로 바꾼다. */
export function geokSentence(god: string, name: { ko: string; hanja: string }, byTouchul: boolean): string {
  const p = GEOK_PARTS[god]!
  const ko = GOD_KO[god]!
  const bold = `**${ko}(${god})**${iga(ko)}`
  const where = byTouchul ? `월지의 숨은 글자 ${p.gloss ?? ''}${bold} 천간에 드러나` : `월지에 ${p.gloss ?? ''}${bold} 앉아`
  return `**${name.ko}(${name.hanja})**입니다. ${p.extra ?? ''}사주에서 가장 무거운 자리인 ${where} 이 명식의 중심이 됩니다. ${p.tail}`
}

/** byTouchul일 때 덧붙이는 안내. */
export function touchulSentence(mainGod: string, god: string): string {
  const m = GOD_KO[mainGod]!, g = GOD_KO[god]!
  return `월지 겉 글자는 **${m}(${mainGod})**이지만, 숨은 글자 가운데 천간에 드러난 **${g}(${god})**${eulreul(g)} 중심으로 읽는 전통 방법을 따랐습니다.`
}

